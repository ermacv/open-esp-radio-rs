#[test]
fn recorded_message3_authenticates_and_retains_its_gtk_wire_id() {
    let frame = EapolKeyFrame::parse(&MESSAGE3).unwrap();
    assert_eq!(frame.message(), EapolKeyMessage::PairwiseMessage3);
    let pmk = Pmk::derive(b"open-esp-radio-m3", b"oer-m3-784").unwrap();
    let ptk = pmk.derive_ptk(
        Akm::PskSha256,
        PtkContext {
            authenticator_address: [0xbe, 0xfc, 0xe7, 0xae, 0xbb, 0xd4],
            supplicant_address: [0x1c, 0xed, 0x6f, 0xb9, 0xba, 0x3c],
            authenticator_nonce: *frame.nonce(),
            supplicant_nonce: SNONCE,
        },
    );
    assert!(frame.verify_mic(&ptk));
    let plain = crate::aes::software_aes128_key_unwrap(ptk.kek(), frame.key_data()).unwrap();
    let keys = parse_gtk_key_data(plain.as_bytes(), &RSN_IE, &[], true).unwrap();
    assert_eq!(keys.gtk.key_id().get(), 1);
    assert_eq!(keys.gtk.key(), &GTK);
    assert!(!keys.gtk.transmit());
    assert_eq!(keys.igtk.unwrap().key_id(), 4);

    // Variants of the recorded KDE exercise every two-bit wire ID. Only
    // the KeyID field changes; these are derived cases, not extra captures.
    for raw_id in 0..=3 {
        let mut changed = std::vec::Vec::from(plain.as_bytes());
        changed[28] = raw_id;
        let keys = parse_gtk_key_data(&changed, &RSN_IE, &[], true).unwrap();
        let install = crate::keys::RsnKeyInstall::group(
            crate::RsnInterface::Station,
            &keys.gtk,
            *frame.key_receive_sequence(),
        );
        assert_eq!(
            install.kind(),
            crate::keys::RsnKeyKind::Group {
                key_id: oer_ieee80211_mac::ccmp::GroupKeyId::new(raw_id).unwrap(),
                transmit: false,
            }
        );
        assert_eq!(install.key().as_bytes(), &GTK);
    }
}
