fn arena_bytes(kind: RateScheduleKind) -> &'static [u8] {
    match kind {
        RateScheduleKind::BarOfdm => BAR_OFDM_SCHEDULE.as_slice(),
        RateScheduleKind::BasicOfdm => BASIC_OFDM_SCHEDULE.as_slice(),
        RateScheduleKind::Dot11Ax => DOT11_AX_SCHEDULE.as_slice(),
        RateScheduleKind::Dot11B => DOT11_B_SCHEDULE.as_slice(),
        RateScheduleKind::Dot11G => DOT11_G_SCHEDULE.as_slice(),
        RateScheduleKind::Dot11N => DOT11_N_SCHEDULE.as_slice(),
        RateScheduleKind::Lora => LORA_SCHEDULE.as_slice(),
        RateScheduleKind::P2pDot11G => P2P_DOT11_G_SCHEDULE.as_slice(),
        RateScheduleKind::P2pDot11N => P2P_DOT11_N_SCHEDULE.as_slice(),
    }
}

fn schedule_bytes(schedule: RateScheduleRef) -> &'static [u8] {
    let offset = usize::from(schedule.index) * RATE_SCHEDULE_RECORD_SIZE;
    &arena_bytes(schedule.kind)[offset..offset + RATE_SCHEDULE_RECORD_SIZE]
}

pub fn schedule_state(schedule: RateScheduleRef) -> RateScheduleRecordState {
    let record = schedule_bytes(schedule);
    RateScheduleRecordState {
        rate: record[0],
        retry_limit: record[1],
        index: record[0x0a],
        adaptive: record[0x0b],
    }
}

/// Return the complete ordinary-MPDU publication budget carried by one
/// vendor rate record.
///
/// SOURCE(esp32s31): complete `libpp.a[trc.o]::rcReachRetryLimit`. Outside the mesh
/// special case it compares the MPDU retry counter with record byte `0x08`;
/// this is independent of byte `0x01`, which `rcTxUpdatePer` consumes as its
/// PER/rate-control threshold.
pub fn schedule_publication_limit(schedule: RateScheduleRef) -> u8 {
    schedule_bytes(schedule)[0x08]
}

/// Select the rate byte for a non-aggregate retry counter.
///
/// Each vendor record starts with four `(rate, attempt_count)` pairs.
/// `rcGetRate` accumulates the four counts and selects the first rate for which
/// `failed_attempts < cumulative_count`. Returning `None` means that the
/// record's complete retry budget has been consumed.
///
/// SOURCE(esp32s31): complete pinned `libpp.a[trc.o]::rcGetRate` (`0xf6` bytes),
/// especially the bounded four-iteration loop at offsets `0xa8..0xf4`;
/// cross-checked against `SOURCE(esp32s31)[PROMOTED_LMAC_TX]`. After the loop the
/// pinned body replaces a selected code of `0x24` or above with `0x10` when
/// descriptor byte `+0x32` bit zero marks an HT-Control MPDU (set only by
/// `ieee80211_encap_esfbuf_htc`). No record this driver selects through the
/// loop holds such a code together with that flag, so the rewrite never
/// applies here.
pub fn schedule_rate_after_failures(schedule: RateScheduleRef, failed_attempts: u8) -> Option<u8> {
    let record = schedule_bytes(schedule);
    let mut cumulative = 0_u8;
    for index in 0..4 {
        let rate = record[index * 2];
        let count = record[index * 2 + 1];
        cumulative = cumulative.wrapping_add(count);
        if failed_attempts < cumulative {
            return Some(rate);
        }
    }
    None
}

/// The `libpp.a[trc.o]` rate-code-to-record callbacks of `rcUpdatePhyMode`.
///
/// The numeric values are still part of the vendor ABI. Keeping the family
/// separate from the callback address prevents safe policy from
/// manufacturing or following a C function pointer.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum RateIndexMap {
    Dot11B,
    Dot11G,
    Dot11N,
    Dot11Ax,
    Lora,
}

/// Pure rate-code callback policy stored temporarily at record offset 0x78;
/// `0xff` when the map has no record for the code.
pub const fn rate_to_schedule_index(map: RateIndexMap, rate: u8) -> u8 {
    match map {
        RateIndexMap::Dot11B => {
            const MAP: [u8; 43] = [
                3, 2, 1, 0, 0xff, 2, 1, 0, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff,
                0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff,
                0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 5, 4,
            ];
            if rate <= 42 { MAP[rate as usize] } else { 0xff }
        }
        RateIndexMap::Dot11G => {
            // SOURCE(esp32s31): `libpp.a[trc.o]` `.rodata` switch table of
            // `rc11GRate2SchedIdx`, including the long-range codes 0x29 and
            // 0x2a that select 802.11g records 12 and 11.
            const MAP: [u8; 43] = [
                10, 9, 8, 0xff, 0xff, 9, 8, 0xff, 1, 3, 5, 7, 0, 2, 4, 6, 0xff, 0xff, 0xff, 0xff,
                0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff,
                0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 12, 11,
            ];
            if rate <= 42 { MAP[rate as usize] } else { 0xff }
        }
        RateIndexMap::Dot11N => match rate {
            0 => 11,
            1 => 10,
            2 => 9,
            3 | 4 => 24_u8.wrapping_sub(rate),
            5 => 10,
            6 => 9,
            0x21 => 0,
            0x29 => 13,
            0x2a => 12,
            _ => 24_u8.wrapping_sub(rate),
        },
        RateIndexMap::Dot11Ax => match rate {
            0 => 13,
            1 => 12,
            2 => 11,
            3 | 4 => 26_u8.wrapping_sub(rate),
            5 => 12,
            6 => 11,
            0x17 => 3,
            0x19 => 1,
            0x22 => 2,
            0x23 => 0,
            0x29 => 15,
            0x2a => 14,
            _ => 26_u8.wrapping_sub(rate),
        },
        RateIndexMap::Lora => match rate {
            0x29 => 1,
            0x2a => 0,
            _ => 0xff,
        },
    }
}

/// Locate the complete vendor 802.11g retry record for a legacy rate code.
///
/// SOURCE(esp32s31): `libpp.a[trc.o]` callback table used by `rcUpdatePhyMode`, the
/// [`RateIndexMap::Dot11G`] branch of [`rate_to_schedule_index`]; the
/// pointed-to record bytes come from the arenas above.
pub const fn dot11g_schedule_for_legacy_rate(rate: u8) -> Option<RateScheduleRef> {
    let index = rate_to_schedule_index(RateIndexMap::Dot11G, rate);
    if index == 0xff {
        None
    } else {
        RateScheduleRef::new(RateScheduleKind::Dot11G, index)
    }
}

