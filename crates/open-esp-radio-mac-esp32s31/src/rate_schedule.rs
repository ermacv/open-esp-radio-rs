//! Rust-owned ESP32-S31 transmit-rate schedule arenas.
//!
//! The nine vendor arenas are fixed arrays of 12-byte records.  `rcAttach`
//! performs only one mutation: it writes each record's zero-based arena index
//! to byte `0x0a`.  The definitions below materialize that post-attach state
//! at compile time, so strict runtime never needs the vendor tables or their
//! initializer.

use core::cell::UnsafeCell;

pub const RATE_SCHEDULE_RECORD_SIZE: usize = 12;

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
#[repr(u8)]
pub enum RateScheduleKind {
    // Deliberately sparse internal tags keep LLVM from materializing a
    // nine-pointer jump table in internal SRAM.  These values never cross the
    // source-owned schedule identity.
    BarOfdm = 0x03,
    BasicOfdm = 0x19,
    Dot11Ax = 0x2f,
    Dot11B = 0x44,
    Dot11G = 0x62,
    Dot11N = 0x83,
    Lora = 0xa1,
    P2pDot11G = 0xc8,
    P2pDot11N = 0xf1,
}

const RATE_SCHEDULE_KINDS: [RateScheduleKind; 9] = [
    RateScheduleKind::BarOfdm,
    RateScheduleKind::BasicOfdm,
    RateScheduleKind::Dot11Ax,
    RateScheduleKind::Dot11B,
    RateScheduleKind::Dot11G,
    RateScheduleKind::Dot11N,
    RateScheduleKind::Lora,
    RateScheduleKind::P2pDot11G,
    RateScheduleKind::P2pDot11N,
];

impl RateScheduleKind {
    pub const fn record_count(self) -> usize {
        match self {
            Self::BarOfdm | Self::BasicOfdm => 1,
            Self::Dot11Ax => 16,
            Self::Dot11B => 6,
            Self::Dot11G => 13,
            Self::Dot11N => 14,
            Self::Lora => 2,
            Self::P2pDot11G => 8,
            Self::P2pDot11N => 10,
        }
    }
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct RateScheduleRef {
    pub kind: RateScheduleKind,
    pub index: u8,
}

impl RateScheduleRef {
    pub const fn new(kind: RateScheduleKind, index: u8) -> Option<Self> {
        if (index as usize) < kind.record_count() {
            Some(Self { kind, index })
        } else {
            None
        }
    }

    pub const fn advance(self) -> Option<Self> {
        Self::new(self.kind, self.index.wrapping_add(1))
    }

    pub const fn offset(self, records: u8) -> Option<Self> {
        let index = self.index as u16 + records as u16;
        if index <= u8::MAX as u16 {
            Self::new(self.kind, index as u8)
        } else {
            None
        }
    }
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct RateScheduleRecordState {
    pub rate: u8,
    pub retry_limit: u8,
    pub index: u8,
    pub adaptive: u8,
}

#[repr(C, align(4))]
struct ScheduleArena<const BYTES: usize>(UnsafeCell<[u8; BYTES]>);

impl<const BYTES: usize> ScheduleArena<BYTES> {
    const fn indexed(mut bytes: [u8; BYTES]) -> Self {
        assert!(BYTES % RATE_SCHEDULE_RECORD_SIZE == 0);
        let mut record = 0;
        while record < BYTES / RATE_SCHEDULE_RECORD_SIZE {
            bytes[record * RATE_SCHEDULE_RECORD_SIZE + 0x0a] = record as u8;
            record += 1;
        }
        Self(UnsafeCell::new(bytes))
    }

    fn as_mut_ptr(&self) -> *mut u8 {
        self.0.get().cast::<u8>()
    }
}

// The radio owner is the only consumer. The post-`rcAttach` contents are
// materialized at compile time and treated as immutable.
unsafe impl<const BYTES: usize> Sync for ScheduleArena<BYTES> {}

