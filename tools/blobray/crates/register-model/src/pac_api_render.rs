fn field_input_transform_expression(
    wrapping_add: u32,
    wrapping_subtract: u32,
    clamp_maximum: Option<u32>,
    retain_mask: u32,
) -> String {
    let arithmetic = if wrapping_add != 0 {
        format!("input.wrapping_add(0x{wrapping_add:08x})")
    } else {
        format!("input.wrapping_sub(0x{wrapping_subtract:08x})")
    };
    let bounded = clamp_maximum.map_or(arithmetic.clone(), |maximum| {
        format!("{arithmetic}.min(0x{maximum:08x})")
    });
    format!("let input = {bounded} & 0x{retain_mask:08x};\n                         ")
}

fn domain_value_expression(domain: &str, flag_or_enum_domains: &BTreeSet<&str>) -> &'static str {
    if flag_or_enum_domains.contains(domain) {
        "value.bits()"
    } else {
        "value.get()"
    }
}

fn push_doc(output: &mut String, description: &str, indent: &str) {
    for line in description.lines() {
        output.push_str(indent);
        output.push_str("///");
        if !line.is_empty() {
            output.push(' ');
            output.push_str(line);
        }
        output.push('\n');
    }
}

fn too_many_arguments_attribute(field_count: usize, is_array: bool) -> &'static str {
    if field_count + usize::from(is_array) > 6 {
        "    #[allow(clippy::too_many_arguments, reason = \"reviewed hardware transaction exposes one typed argument per field\")]\n"
    } else {
        ""
    }
}

fn masked_image_expression(preserve_mask: u32, input_mask: u32, set_mask: u32) -> String {
    let mut expression =
        format!("(reader.bits() & 0x{preserve_mask:08x}) | (input & 0x{input_mask:08x})");
    if set_mask != 0 {
        expression.push_str(&format!(" | 0x{set_mask:08x}"));
    }
    expression
}

fn remove_dimension_placeholder(value: &str) -> String {
    value.replace("[%s]", "").replace("%s", "")
}

fn member_binding_name(value: &str) -> String {
    remove_dimension_placeholder(value).to_ascii_lowercase()
}

fn type_binding_name(value: &str) -> String {
    let value = remove_dimension_placeholder(value);
    let mut output = String::new();
    let mut previous_ended_with_digit = false;
    for part in value.split(['_', '-']).filter(|part| !part.is_empty()) {
        if previous_ended_with_digit
            && part.starts_with(|character: char| character.is_ascii_digit())
        {
            output.push('_');
        }
        for (index, character) in part.chars().enumerate() {
            if index == 0 {
                output.push(character.to_ascii_uppercase());
            } else {
                output.push(character.to_ascii_lowercase());
            }
        }
        previous_ended_with_digit = part.ends_with(|character: char| character.is_ascii_digit());
    }
    output
}

fn device_access_api() -> &'static str {
    "\n/// Architecture-specific device-memory ordering primitives.\n\
     pub mod device_access {\n\
         /// Order all preceding and following device-memory accesses.\n\
         #[inline]\n\
         pub fn fence() {\n\
             #[cfg(target_arch = \"riscv32\")]\n\
             // SAFETY: this instruction only orders memory and device accesses.\n\
             unsafe { core::arch::asm!(\"fence iorw, iorw\") }\n\
             #[cfg(target_arch = \"arm\")]\n\
             // SAFETY: this instruction only orders memory and device accesses.\n\
             unsafe { core::arch::asm!(\"dmb sy\") }\n\
             #[cfg(target_arch = \"xtensa\")]\n\
             // SAFETY: this instruction only orders memory and device accesses.\n\
             unsafe { core::arch::asm!(\"memw\") }\n\
             #[cfg(not(any(\n\
                 target_arch = \"riscv32\",\n\
                 target_arch = \"arm\",\n\
                 target_arch = \"xtensa\",\n\
             )))]\n\
             core::sync::atomic::compiler_fence(core::sync::atomic::Ordering::SeqCst);\n\
         }\n\
     }\n"
}

